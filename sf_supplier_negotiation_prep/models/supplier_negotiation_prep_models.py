# -*- coding: utf-8 -*-
"""Supplier Negotiation Prep models"""
from odoo import api, fields, models, _
from odoo.exceptions import UserError


class SfSupplier_negotiation_prep(models.Model):
    _name = 'sf.supplier_negotiation_prep'
    _description = 'Supplier Negotiation Prep'
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'create_date desc, id desc'

    name = fields.Char(string='Reference', required=True, copy=False, readonly=True, default='New')
    company_id = fields.Many2one('res.company', string='Company', required=True, default=lambda s: s.env.company, tracking=True)
    vendor_id = fields.Many2one('res.partner', string='Supplier', required=True)
    negotiation_date = fields.Date(string='Negotiation Date', required=True)
    leverage_points = fields.Html(string='Leverage Points')
    target_outcome = fields.Text(string='Target Outcome')
    batna = fields.Text(string='BATNA (Best Alternative)')
    negotiator_id = fields.Many2one('res.users', string='Negotiator')
    currency_id = fields.Many2one(related='company_id.currency_id')
    state = fields.Selection([
        ('draft', 'Draft'),
        ('submitted', 'Submitted'),
        ('done', 'Done'),
        ], string='Status', default='draft', tracking=True, copy=False)

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('name', 'New') == 'New':
                vals['name'] = self.env['ir.sequence'].next_by_code(
                    'sf.supplier_negotiation_prep') or 'NEW'
        return super().create(vals_list)

    def action_submitted(self):
        self.write({'state': 'submitted'})

    def action_done(self):
        self.write({'state': 'done'})

